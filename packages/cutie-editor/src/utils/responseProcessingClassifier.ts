import { parseNumber, parseNumericBaseValue, roundScore } from '@openstax/cutie-core';
import { domToXmlNode } from '../serialization/xmlNode.js';
import { parseXml } from '../serialization/xmlUtils.js';
import type { ResponseProcessingConfig, ResponseProcessingSettings, SerializationResult } from '../types.js';
import { getDeclaredMaximumScore } from './maximumScore.js';
import { TEMPLATES } from './responseProcessingGenerator.js';

/**
 * Save the item as loaded, with the given response processing config
 */
export type RegenerateItem = (config: ResponseProcessingConfig) => SerializationResult;

/**
 * The name of a response processing template from its URL: the last segment,
 * without .xml (the spec's examples use the purl and older www URLs, with and
 * without .xml). Only templates hosted by 1EdTech (imsglobal.org) are named;
 * any other URL is returned as is.
 */
function templateName(url: string): string {
  try {
    const { hostname, pathname } = new URL(url);
    if (hostname !== 'imsglobal.org' && !hostname.endsWith('.imsglobal.org')) return url;
    return pathname.split('/').pop()!.replace(/\.xml$/, '');
  } catch {
    return url;
  }
}

/**
 * Whether a template URL names one of the standard templates the editor generates
 */
function isManagedTemplate(url: string): boolean {
  return Object.values(TEMPLATES).some((template) => templateName(template) === templateName(url));
}

/**
 * Get the responses an item's response processing scores. For a standard
 * template that's RESPONSE; for inline rules, every declared response they
 * reference outside feedback-only conditions (whose rules only set FEEDBACK).
 * Unknown templates score unknown responses, so none are reported.
 *
 * @param doc - The QTI XML document
 * @returns Identifiers of the scored responses
 */
export function getScoredResponseIdentifiers(doc: Document): Set<string> {
  const scored = new Set<string>();
  const responseProcessing = doc.querySelector('qti-response-processing');
  if (!responseProcessing) return scored;

  const declared = new Set(
    Array.from(doc.querySelectorAll('qti-response-declaration')).map((decl) => decl.getAttribute('identifier'))
  );

  const template = responseProcessing.getAttribute('template');
  if (template) {
    if (isManagedTemplate(template) && declared.has('RESPONSE')) {
      scored.add('RESPONSE');
    }
    return scored;
  }

  const isFeedbackOnly = (condition: Element) => {
    const rules = Array.from(condition.querySelectorAll('qti-set-outcome-value'));
    return rules.length > 0 && rules.every((rule) => rule.getAttribute('identifier') === 'FEEDBACK');
  };

  for (const reference of responseProcessing.querySelectorAll('[identifier]')) {
    const identifier = reference.getAttribute('identifier');
    if (!identifier || !declared.has(identifier)) continue;
    const condition = reference.closest('qti-response-condition');
    if (condition && isFeedbackOnly(condition)) continue;
    scored.add(identifier);
  }

  return scored;
}

/**
 * Classify an item's response processing into a mode.
 *
 * Response processing belongs to a managed mode only if saving the item in that
 * mode would write it back the same: each candidate config is regenerated by
 * saving the item, and the first whose response processing matches the loaded
 * one (see canonicalResponseProcessing), and whose MAXSCORE matches any the
 * item declares, is the item's mode. Anything else is kept as custom.
 * Candidates are tried in order:
 *
 * 1. allCorrect
 * 2. sumScores, with the score offset and maximum score read from the SCORE rule
 *
 * Checked first: SCORE declared external-scored="human" -> manual, and
 * external-scored="externalMachine" -> custom (not managed by the editor).
 * Without response processing, or with an empty one, the item defaults to allCorrect.
 *
 * @param doc - The QTI XML document, as loaded
 * @param regenerate - Saves the item as loaded with a given config
 * @returns The item's response processing config
 */
export function classifyResponseProcessing(doc: Document, regenerate: RegenerateItem): ResponseProcessingConfig {
  const responseProcessing = doc.querySelector('qti-response-processing');

  // SCORE set outside response processing
  const externalScored = doc
    .querySelector('qti-outcome-declaration[identifier="SCORE"]')
    ?.getAttribute('external-scored');
  if (externalScored === 'human') {
    return { mode: 'manual' };
  }
  if (externalScored === 'externalMachine') {
    return responseProcessing
      ? { mode: 'custom', customXml: domToXmlNode(responseProcessing) }
      : { mode: 'custom' };
  }

  if (!responseProcessing || (!responseProcessing.children.length && !responseProcessing.hasAttribute('template'))) {
    return { mode: 'allCorrect' };
  }

  const loaded = canonicalResponseProcessing(responseProcessing);
  const candidates: ResponseProcessingConfig[] = [
    { mode: 'allCorrect' },
    { mode: 'sumScores', ...readSumScoresSettings(responseProcessing) },
  ];

  for (const candidate of candidates) {
    const result = regenerate(candidate);
    const regeneratedDoc = result.errors?.length ? null : parseXml(result.xml);
    const regenerated = regeneratedDoc?.querySelector('qti-response-processing');
    if (!regenerated || canonicalResponseProcessing(regenerated) !== loaded) continue;

    // The editor manages MAXSCORE, so a declared one must be what it would declare
    const declared = getDeclaredMaximumScore(doc);
    if (declared === null || roundScore(declared) === getDeclaredMaximumScore(regeneratedDoc!)) {
      return candidate;
    }
  }

  return { mode: 'custom', customXml: domToXmlNode(responseProcessing) };
}

/**
 * Read the sumScores settings from the rule that sets SCORE, if there is one: a
 * qti-min with a number (the maximum score) and a number in the qti-sum (the
 * score offset), around and inside any qti-max (the floor). Anything the
 * generator wouldn't write is left for the comparison to reject.
 */
function readSumScoresSettings(responseProcessing: Element): ResponseProcessingSettings {
  const settings: ResponseProcessingSettings = {};
  const setScore = Array.from(responseProcessing.children).find((rule) =>
    rule.localName === 'qti-set-outcome-value' && rule.getAttribute('identifier') === 'SCORE');

  let expression = setScore?.firstElementChild;
  while (expression && (expression.localName === 'qti-min' || expression.localName === 'qti-max')) {
    const operands = Array.from(expression.children);
    const constant = operands.find((operand) => parseNumericBaseValue(operand) !== null);
    if (expression.localName === 'qti-min' && constant) {
      settings.maximumScore = parseNumericBaseValue(constant)!;
    }
    expression = operands.find((operand) => operand !== constant);
  }

  if (expression?.localName === 'qti-sum') {
    const offset = Array.from(expression.children)
      .map(parseNumericBaseValue)
      .find((value) => value !== null);
    if (offset) settings.scoreOffset = offset;
  }
  return settings;
}

/**
 * Operators whose operands can come in any order
 */
const COMMUTATIVE_OPERATORS = new Set(['qti-and', 'qti-sum', 'qti-min', 'qti-max']);

/**
 * Numeric base types, whose values are compared as numbers
 */
const NUMERIC_BASE_TYPES = new Set(['float', 'integer']);

/**
 * Canonical text of response processing, equal for response processing that
 * the generator would write the same. It ignores:
 *
 * - whitespace, comments, namespace declarations and attribute order
 * - how numbers are written (1 and 1.0, integer and float base values)
 * - the template URL, beyond the name of a standard template (see templateName)
 * - the order of the operands of qti-and, qti-sum, qti-min and qti-max
 * - a 0 in a qti-sum
 * - the floor on SCORE (a qti-max with 0 around the sum, inside or outside a
 *   qti-min): it isn't a setting, the generator adds it whenever the score could
 *   be negative, so a floor that isn't needed is dropped on save and one that is
 *   needed is added
 */
function canonicalResponseProcessing(responseProcessing: Element): string {
  return canonicalize(responseProcessing, false);
}

/**
 * Canonical text of an element (see canonicalResponseProcessing)
 *
 * @param element - The element
 * @param scoreBound - Whether the element is SCORE's expression, or the operand
 *   of a qti-min or qti-max that is, where the floor is ignored
 */
function canonicalize(element: Element, scoreBound: boolean): string {
  const tag = element.localName;
  const operands = Array.from(element.children);

  if (scoreBound && tag === 'qti-max' && operands.length === 2) {
    const floor = operands.findIndex((operand) => parseNumericBaseValue(operand) === 0);
    if (floor !== -1) return canonicalize(operands[1 - floor], true);
  }

  const attributes = Array.from(element.attributes)
    .filter((attribute) => attribute.name !== 'xmlns' && !attribute.name.startsWith('xmlns:'))
    .map((attribute) => {
      if (tag === 'qti-response-processing' && attribute.name === 'template') {
        return `template=${JSON.stringify(templateName(attribute.value))}`;
      }
      return `${attribute.name}=${JSON.stringify(attribute.value)}`;
    });

  if (tag === 'qti-base-value' && NUMERIC_BASE_TYPES.has(element.getAttribute('base-type') ?? '')) {
    const value = parseNumber(element.textContent ?? '');
    if (value !== null) return `<qti-base-value number>${value}</qti-base-value>`;
  }

  const childBound = (tag === 'qti-set-outcome-value' && element.getAttribute('identifier') === 'SCORE') ||
    (scoreBound && (tag === 'qti-min' || tag === 'qti-max'));
  let children = Array.from(element.childNodes).flatMap((child) => {
    if (child.nodeType === child.ELEMENT_NODE) return [canonicalize(child as Element, childBound)];
    const text = child.nodeType === child.TEXT_NODE ? child.textContent?.trim() : '';
    return text ? [JSON.stringify(text)] : [];
  });
  if (tag === 'qti-sum') {
    children = children.filter((child) => child !== '<qti-base-value number>0</qti-base-value>');
  }
  if (COMMUTATIVE_OPERATORS.has(tag)) {
    children.sort();
  }

  return `<${tag} ${attributes.sort().join(' ')}>${children.join('')}</${tag}>`;
}
